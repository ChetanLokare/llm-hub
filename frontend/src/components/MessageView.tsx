import { Check, Copy, Download, FileText, Pencil, RefreshCw, Sparkles, X } from 'lucide-react';
import { useState } from 'react';
import { fileUrl } from '../api';
import type { ChatMessage, LocalFile, StoredFile } from '../types';
import { copyText, fmtSize } from '../util';
import { Markdown } from './Markdown';

type Props = {
  msg: ChatMessage; chatId: string | null; isLast: boolean; busy: boolean;
  onEdit: (id: number, text: string, keepFiles: boolean) => void;
  onRegenerate: () => void;
};

function FileChips({ chatId, files, local }: { chatId: string | null; files?: StoredFile[]; local?: LocalFile[] }) {
  const items: Array<{ key: string; name: string; size: number; kind: string; url?: string; stored: boolean }> = [
    ...(files || []).map(f => ({ key: `s${f.id}`, name: f.name, size: f.size, kind: f.kind, url: chatId && f.stored ? fileUrl(chatId, f.id) : undefined, stored: f.stored })),
    ...(local || []).map((f, i) => ({ key: `l${i}`, name: f.name, size: f.size, kind: f.mime_type.startsWith('image/') ? 'image' : 'other', url: f.previewUrl, stored: true })),
  ];
  if (!items.length) return null;
  return (
    <div className="msg-files">
      {items.map(f => f.kind === 'image' && f.url
        ? <a key={f.key} href={f.url} target="_blank" rel="noreferrer" className="msg-thumb" title={`${f.name} · ${fmtSize(f.size)}`}><img src={f.url} alt={f.name} /></a>
        : <span key={f.key} className="msg-file" title={f.stored ? '' : 'The original file is no longer stored; its text is still in the conversation.'}>
            <FileText size={13} />{f.url ? <a href={f.url} target="_blank" rel="noreferrer">{f.name}</a> : f.name} · {fmtSize(f.size)}
          </span>)}
    </div>
  );
}

export function MessageView({ msg, chatId, isLast, busy, onEdit, onRegenerate }: Props) {
  const [editing, setEditing] = useState(false);
  const [draft, setDraft] = useState(msg.content);
  const [keepFiles, setKeepFiles] = useState(true);
  const [copied, setCopied] = useState(false);
  const isUser = msg.role === 'user';
  const hasFiles = Boolean(msg.files?.length);

  const copy = async () => { if (await copyText(msg.content)) { setCopied(true); window.setTimeout(() => setCopied(false), 1500); } };
  const save = () => { if (msg.id != null && (draft.trim() || (hasFiles && keepFiles))) { setEditing(false); onEdit(msg.id, draft, keepFiles); } };

  return (
    <div className={`message-row ${msg.role}`}>
      <div className={`message-avatar ${isUser ? 'user-avatar' : 'assistant-avatar'}`}>{isUser ? 'Y' : <Sparkles size={16} />}</div>
      <div className="message-content">
        <div className="message-meta">
          <strong>{isUser ? 'You' : 'LLM Hub'}</strong>
          {!isUser && (msg.provider || msg.model) && <span>{msg.provider}{msg.model ? ` · ${msg.model}` : ''}</span>}
        </div>
        {!isUser && msg.note && <small className="route-note">{msg.note}</small>}
        <div className={`bubble ${isUser ? 'user-bubble' : 'assistant-bubble'}`}>
          {isUser && editing ? (
            <div className="edit-box">
              <textarea value={draft} autoFocus rows={Math.min(10, Math.max(3, draft.split('\n').length))} onChange={e => setDraft(e.target.value)}
                onKeyDown={e => { if (e.key === 'Enter' && (e.ctrlKey || e.metaKey)) { e.preventDefault(); save(); } if (e.key === 'Escape') setEditing(false); }} />
              {hasFiles && <label className="keep-files"><input type="checkbox" checked={keepFiles} onChange={e => setKeepFiles(e.target.checked)} /> Keep the {msg.files!.length} attached file(s)</label>}
              <div className="edit-actions">
                <button className="settings-button" onClick={() => setEditing(false)}><X size={13} /> Cancel</button>
                <button className="primary-wide" onClick={save} disabled={busy}>Save &amp; resend</button>
              </div>
              <small>Messages after this one are replaced by the new answer. Ctrl+Enter to send.</small>
            </div>
          ) : isUser ? (
            <><p className="user-text">{msg.content}</p><FileChips chatId={chatId} files={msg.files} local={msg.localFiles} /></>
          ) : (
            <>
              <Markdown text={msg.content} />
              {msg.images && msg.images.length > 0 && (
                <div className="generated-images">
                  {msg.images.map((img, j) => {
                    const src = `data:${img.mime_type};base64,${img.data}`;
                    const ext = img.mime_type.split('/')[1] === 'jpeg' ? 'jpg' : img.mime_type.split('/')[1];
                    return <figure key={j}><img src={src} alt="Image generated by the model" />
                      <a className="settings-button" href={src} download={`generated-image-${j + 1}.${ext}`}><Download size={13} /> Download</a></figure>;
                  })}
                </div>
              )}
            </>
          )}
          {!editing && (
            <div className="message-actions">
              <button onClick={() => void copy()} title="Copy message">{copied ? <><Check size={13} /> Copied</> : <><Copy size={13} /> Copy</>}</button>
              {isUser && msg.id != null && !busy && <button onClick={() => { setDraft(msg.content); setKeepFiles(true); setEditing(true); }} title="Edit this message and resend"><Pencil size={13} /> Edit</button>}
              {!isUser && isLast && !busy && <button onClick={onRegenerate} title="Answer again with the model chosen in the picker"><RefreshCw size={13} /> Regenerate</button>}
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
